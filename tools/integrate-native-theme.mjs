import fs from 'node:fs'
import path from 'node:path'
export function integrateNativeTheme(source) {
  const schemaPath = path.join(source, 'common/extensions/api/brave_theme.json')
  const rawSchema = fs.readFileSync(schemaPath, 'utf8')
  const schema = JSON.parse(rawSchema.replace(/^\s*\/\/.*$/gm, ''))
  schema[0].functions = schema[0].functions.filter(item => item.name !== 'setVeyrionColor')
  schema[0].functions.push({
    name: 'setVeyrionColor', type: 'function',
    description: 'Apply the Veyrion accent to the native browser theme.',
    parameters: ['red', 'green', 'blue'].map(name => ({ name, type: 'integer' })),
    returns_async: { name: 'callback', parameters: [{ name: 'color', type: 'integer' }] }
  })
  const license = rawSchema.match(/^(?:\/\/[^\n]*\n)+/)?.[0] || ''
  fs.writeFileSync(schemaPath, license + '\n' + JSON.stringify(schema, null, 2) + '\n')
  const headerPath = path.join(source, 'browser/extensions/api/brave_theme_api.h')
  let header = fs.readFileSync(headerPath, 'utf8')
  if (!header.includes('class BraveThemeSetVeyrionColorFunction')) {
    header = header.replace('}  // namespace api', `class BraveThemeSetVeyrionColorFunction : public ExtensionFunction {
 public:
  DECLARE_EXTENSION_FUNCTION("braveTheme.setVeyrionColor", UNKNOWN)

 protected:
  ~BraveThemeSetVeyrionColorFunction() override = default;
  ResponseAction Run() override;
};

}  // namespace api`)
    fs.writeFileSync(headerPath, header)
  }
  const implementationPath = path.join(source, 'browser/extensions/api/brave_theme_api.cc')
  let implementation = fs.readFileSync(implementationPath, 'utf8')
  if (!implementation.includes('BraveThemeSetVeyrionColorFunction::Run()')) {
    implementation = implementation.replace('#include "base/notreached.h"', '#include "base/check.h"\n#include "base/notreached.h"')
      .replace('#include "chrome/browser/themes/theme_service_factory.h"', '#include "chrome/browser/themes/theme_service_factory.h"\n#include "third_party/skia/include/core/SkColor.h"')
      .replace('}  // namespace extensions::api', `ExtensionFunction::ResponseAction BraveThemeSetVeyrionColorFunction::Run() {
  auto params = brave_theme::SetVeyrionColor::Params::Create(args());
  EXTENSION_FUNCTION_VALIDATE(params);
  if (params->red < 0 || params->red > 255 || params->green < 0 ||
      params->green > 255 || params->blue < 0 || params->blue > 255) {
    return RespondNow(Error("Color channels must be between 0 and 255."));
  }
  auto* theme_service = ThemeServiceFactory::GetForProfile(
      Profile::FromBrowserContext(browser_context()));
  CHECK(theme_service);
  theme_service->SetBrowserColorScheme(ThemeService::BrowserColorScheme::kDark);
  theme_service->BuildAutogeneratedThemeFromColor(
      SkColorSetRGB(params->red, params->green, params->blue));
  return RespondNow(WithArguments(static_cast<int>(
      theme_service->GetAutogeneratedThemeColor() & 0x00FFFFFF)));
}

}  // namespace extensions::api`)
    fs.writeFileSync(implementationPath, implementation)
  }
  console.log('Color de Veyrion conectado al tema nativo de pestañas y barra. Pendiente compilación y prueba.')
}
